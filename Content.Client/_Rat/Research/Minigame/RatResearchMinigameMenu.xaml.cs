    private static string ToBinaryString(int value)
    {
        if (value == 0)
            return "00000000";

        var chars = new char[8];
        for (var i = 7; i >= 0; i--)
        {
            chars[i] = (value & 1) == 1 ? '1' : '0';
            value >>= 1;
        }
        return new string(chars);
    }
